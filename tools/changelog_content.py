"""Project the authored remaster changelog above the unchanged imported log."""
from __future__ import annotations

import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PATH = "RESOURCE/INI/texts/russian/Changelog.txt"
BASELINE = ROOT / "experiments/native-metal/inputs/gameplay" / PATH
MARKDOWN = ROOT / "docs/changelog-ru.md"
BASE_SHA256 = "e70e7b446cf88f8669d5a2dbd0902936395b3ffc69d9daaf1512d053c5159a47"
OPENING = b"ChangeLog\r\n{\r\n"


def plain_text(markdown: str) -> str:
    """Remove presentation markup without discarding authored table columns."""
    if any(token in markdown for token in ("\0", "{", "}", "\\n", "\\N", "<color", "</color>")):
        raise ValueError("Changelog text contains native parser delimiters")
    if markdown.count("**") % 2:
        raise ValueError("Unpaired changelog emphasis")
    lines = markdown.replace("**", "").splitlines()
    output = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.startswith("|"):
            output.append(re.sub(r"^#{1,6} ", "", line))
            index += 1
            continue

        def cells(row: str) -> list[str]:
            if not row.endswith("|"):
                raise ValueError("Incomplete changelog table row")
            return [cell.strip() for cell in row[1:-1].split("|")]

        headers = cells(line)
        index += 1
        if index == len(lines) or not lines[index].startswith("|"):
            raise ValueError("Missing changelog table separator")
        separators = cells(lines[index])
        if len(separators) != len(headers) or any(
                not re.fullmatch(r":?-+:?", cell) for cell in separators):
            raise ValueError("Invalid changelog table separator")
        index += 1
        while index < len(lines) and lines[index].startswith("|"):
            row = cells(lines[index])
            if len(row) != len(headers):
                raise ValueError("Changelog table column count changed")
            output.extend(f"{header}: {cell}" for header, cell in zip(headers, row))
            output.append("")
            index += 1
    return "\n".join(output).rstrip() + "\n"


def read():
    """Bind generated bytes and transaction snapshots to the same input reads."""
    paths = (Path(__file__).resolve(), MARKDOWN, BASELINE)
    snapshots = {path: path.read_bytes() for path in paths}
    baseline = snapshots[BASELINE]
    if (hashlib.sha256(baseline).hexdigest() != BASE_SHA256
            or not baseline.startswith(OPENING) or not baseline.endswith(b"}")):
        raise RuntimeError("Imported changelog baseline changed; no files changed")
    text = plain_text(snapshots[MARKDOWN].decode("utf-8"))
    insertion = text.replace("\n", "\r\n").encode("utf-8") + b"\r\n"
    data = OPENING + insertion + baseline[len(OPENING):]
    return ({PATH: (data, (BASE_SHA256,), "utf-8")},
            {path: (data, data) for path, data in snapshots.items()})
