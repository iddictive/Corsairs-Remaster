#include "wdm_warring_ship.h"

// ============================================================================================
// Construction, destruction
// ============================================================================================

WdmWarringShip::WdmWarringShip()
{
    shipType = wdmest_warring;
}

// Calculations
void WdmWarringShip::Update(float dltTime)
{
    WdmEnemyShip::Update(dltTime);
    // help the opponent :)
    if (attack && !GetTrafficData())
    {
        if (!isLive)
            attack->isLive = false;
        if (killMe)
            attack->killMe = true;
    }
}
